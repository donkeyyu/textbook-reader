import type { CustomView, CustomEdit, CustomEntry, CustomDeletion } from './custom-catalog.ts';
import type { LinkIndex } from './links.ts';
import type { MovePlan, MoveStatus } from './moves.ts';
export type Position = { cursor: number; scroll: number };
export type VaultState = { activePath?: string; positions: Record<string, Position>; sidebarWidth?: number };
export type Note = { path: string; source: string; revision: string; readOnly: boolean; problems: string[]; id?: string; fileMtime?: number; duplicatePaths?: string[] };
export type VaultChange = { token: string; notes: string[]; changed: string[]; duplicates: Record<string, string[]>; error?: string };
export type Recovery = { id: string; path: string; created: string; original: string | null; candidate: string; observed?: string };
export type VaultView = { token: string; name: string; notes: string[]; state: VaultState; notice?: string };
export type Result<T> = { ok: true; value: T } | { ok: false; error: string; code?: string };
export type BodyMode = 'edit' | 'preview' | 'live';
export type FrontmatterMode = 'source' | 'properties';
export type PropertyType = 'text' | 'number' | 'boolean' | 'list' | 'date' | 'object';
export type EditorPreferences = { bodyMode: BodyMode; frontmatterMode: FrontmatterMode };
export type VaultSettings = { editor: EditorPreferences; propertyTypes: Record<string, PropertyType> };
export type SettingsView = { revision: string | null; settings: VaultSettings; unsupportedPropertyTypes?: string[] };
export type SettingsPatch = { editor?: Partial<EditorPreferences>; propertyTypes?: Record<string, PropertyType> };
export type DesktopApi = {
  restore: () => Promise<Result<VaultView | null>>;
  chooseVault: () => Promise<Result<VaultView | null>>;
  customCatalog: (token: string) => Promise<Result<CustomView>>;
  saveCustomCatalog: (token: string, revision: string | null, edit: CustomEdit) => Promise<Result<{ view: CustomView; entry: CustomEntry; reused: boolean }>>;
  customDeletions: (token: string) => Promise<Result<CustomDeletion[]>>;
  planCustomDeletion: (token: string, revision: string | null, kind: 'chapter' | 'section', id: string, replacement: string | null) => Promise<Result<CustomDeletion>>;
  applyCustomDeletion: (token: string, id: string) => Promise<Result<CustomDeletion>>;
  links: (token: string) => Promise<Result<LinkIndex>>;
  moveStatus: (token: string) => Promise<Result<MoveStatus>>;
  planMove: (token: string, from: string, to: string, revision: string) => Promise<Result<MovePlan>>;
  planRepair: (token: string, notice: string) => Promise<Result<MovePlan>>;
  applyMove: (token: string, operation: string) => Promise<Result<MovePlan>>;
  list: (token: string) => Promise<Result<string[]>>;
  read: (token: string, path: string) => Promise<Result<Note>>;
  save: (token: string, path: string, source: string, revision: string | null) => Promise<Result<Note>>;
  copy: (token: string, path: string, source: string, revision: string, replaceIdentity: boolean) => Promise<Result<Note>>;
  protectDraft: (token: string, path: string, source: string) => Promise<Result<string>>;
  recoveries: (token: string) => Promise<Result<Recovery[]>>;
  onChange: (callback: (change: VaultChange) => void) => () => void;
  onBeforeClose: (callback: () => Promise<boolean>) => () => void;
  saveState: (token: string, state: VaultState) => Promise<Result<null>>;
  readSettings: (token: string) => Promise<Result<SettingsView>>;
  saveSettings: (token: string, revision: string | null, patch: SettingsPatch) => Promise<Result<SettingsView>>;
  setDirty: (dirty: boolean) => void;
};
